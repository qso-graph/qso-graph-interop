/// Released band() MHz buckets and band_name() labels (S13), including "other".
pub fn band(frequency: f64) -> &'static str {
    let mhz = (frequency / 1_000_000.0) as u64;
    const BANDS: &[(u64, u64, &str)] = &[
        (0, 1, "160m"),
        (3, 3, "80m"),
        (4, 4, "75m"),
        (5, 5, "60m"),
        (7, 7, "40m"),
        (10, 10, "30m"),
        (14, 14, "20m"),
        (18, 18, "17m"),
        (21, 21, "15m"),
        (24, 24, "12m"),
        (28, 29, "10m"),
        (50, 54, "6m"),
        (70, 71, "4m"),
        (144, 148, "2m"),
        (222, 225, "1.25m"),
        (420, 450, "70cm"),
        (902, 928, "33cm"),
        (1240, 1325, "23cm"),
        (2300, 2450, "13cm"),
        (3300, 3500, "9cm"),
        (5650, 5925, "6cm"),
        (10000, 10500, "3cm"),
        (24000, 24250, "1.25cm"),
        (47000, 47200, "6mm"),
        (75500, 81000, "4mm"),
        (119980, 120020, "2.5mm"),
        (142000, 149000, "2mm"),
        (241000, 250000, "1mm"),
    ];
    BANDS
        .iter()
        .find(|(lo, hi, _)| (*lo..=*hi).contains(&mhz))
        .map_or("other", |b| b.2)
}
